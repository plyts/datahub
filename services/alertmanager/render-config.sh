#!/bin/sh
# Alertmanager for the Data Hub: render the configuration from the same notification settings as
# the pipelines (.env), then start Alertmanager. POSIX sh only (the image is busybox-based).
#
#   render-config.sh <output-dir> [alertmanager arguments...]
#
#   NOTIFY_WEBHOOK_URL                Slack-compatible incoming webhook (Slack, Mattermost, Rocket.Chat)
#   SMTP_HOST, SMTP_PORT, SMTP_FROM   SMTP relay (no TLS / no auth, like the pipeline notifications)
#   NOTIFY_EMAIL_TO                   e-mail recipient(s)
#   DATAHUB_ENV                       shown in the notification title
# Nothing configured: alerts are kept in Alertmanager (and visible in Grafana) but sent nowhere.
set -eu

out="${1:?usage: render-config.sh <output-dir> [alertmanager arguments...]}"
shift
mkdir -p "$out"
umask 077

# YAML double-quoted string: escape backslashes and double quotes.
yaml_quote() {
  printf '"%s"' "$(printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g')"
}

env_name="$(printf '%s' "${DATAHUB_ENV:-dev}" | tr '[:lower:]' '[:upper:]')"
webhook="${NOTIFY_WEBHOOK_URL:-}"
smtp_host="${SMTP_HOST:-}"
email_to="${NOTIFY_EMAIL_TO:-}"

receiver="null"
if [ -n "$webhook" ] || { [ -n "$smtp_host" ] && [ -n "$email_to" ]; }; then
  receiver="notify"
fi

{
  cat <<YAML
# Generated by render-config.sh at container start: do not edit.
global:
  resolve_timeout: 5m
route:
  receiver: "${receiver}"
  group_by: [alertname, severity]
  group_wait: 30s
  group_interval: 5m
  repeat_interval: 4h
inhibit_rules:
  - source_matchers: ['severity="critical"']
    target_matchers: ['severity="warning"']
    equal: [alertname]
receivers:
  - name: "null"
  - name: "notify"
YAML
  if [ -n "$webhook" ]; then
    printf '%s' "$webhook" > "$out/webhook_url"
    cat <<YAML
    slack_configs:
      - api_url_file: "$out/webhook_url"
        send_resolved: true
        title: '[Data Hub ${env_name}] {{ .Status | toUpper }} : {{ .CommonLabels.alertname }}'
        text: '{{ range .Alerts }}{{ .Annotations.summary }}{{ "\n" }}{{ end }}'
YAML
  fi
  if [ -n "$smtp_host" ] && [ -n "$email_to" ]; then
    cat <<YAML
    email_configs:
      - to: $(yaml_quote "$email_to")
        from: $(yaml_quote "${SMTP_FROM:-datahub@localhost}")
        smarthost: $(yaml_quote "${smtp_host}:${SMTP_PORT:-25}")
        require_tls: false
        send_resolved: true
        headers:
          Subject: '[Data Hub ${env_name}] {{ .Status | toUpper }} : {{ .CommonLabels.alertname }}'
YAML
  fi
} > "$out/alertmanager.yml"

echo "alertmanager: receiver=${receiver} (webhook: $([ -n "$webhook" ] && echo yes || echo no), e-mail: $([ "$receiver" = notify ] && [ -n "$email_to" ] && [ -n "$smtp_host" ] && echo yes || echo no))"

[ "$#" -gt 0 ] || exit 0
exec /bin/alertmanager "$@"
